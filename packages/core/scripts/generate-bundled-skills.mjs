import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const coreRoot = path.resolve(import.meta.dirname, '..');
const sourcePath = path.join(coreRoot, 'src', 'skills-builtin', 'create-skill', 'SKILL.md');
const outputPath = path.join(coreRoot, 'src', 'modules', 'skills', 'bundled.ts');

function parseSkill(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) {
    throw new Error(`Invalid SKILL.md frontmatter: ${sourcePath}`);
  }

  const metadata = Object.fromEntries(
    match[1]
      .split('\n')
      .filter(Boolean)
      .map((line) => {
        const separator = line.indexOf(':');
        if (separator < 1) {
          throw new Error(`Unsupported frontmatter line: ${line}`);
        }
        return [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
      }),
  );

  if (!metadata.name || !metadata.description) {
    throw new Error('create-skill requires name and description');
  }

  return {
    name: metadata.name,
    description: metadata.description,
    body: match[2].replace(/^\n/, '').replace(/\s+$/, ''),
  };
}

function generateBundledSource(skill) {
  return `// This file is generated by scripts/generate-bundled-skills.mjs. Do not edit manually.\n// Source of truth: src/skills-builtin/create-skill/SKILL.md\n\nimport type { Skill } from './types';\n\nexport const BUNDLED_SKILLS: Skill[] = [\n  {\n    name: ${JSON.stringify(skill.name)},\n    description: ${JSON.stringify(skill.description)},\n    sourcePath: 'builtin:create-skill',\n    source: 'builtin',\n    body: ${JSON.stringify(skill.body)},\n  },\n];\n`;
}

const source = await readFile(sourcePath, 'utf8');
const generated = generateBundledSource(parseSkill(source));

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    console.error('bundled.ts is out of date. Run: pnpm --filter @the-thing/core generate:skills');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated, 'utf8');
  console.log(`Generated ${path.relative(coreRoot, outputPath)} from ${path.relative(coreRoot, sourcePath)}`);
}
