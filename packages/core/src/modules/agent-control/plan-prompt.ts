// ============================================================
// Plan Prompt - 规划提示 (Phase A, 2026-08-15)
// ============================================================
// 原则：
//   - **判断一律交给大模型**（是否复杂 / 是否要规划），代码只做确定性机械活——何时提醒。
//   - **复杂度 = 心智复杂度，不是实现步骤数**。todo 的作用是拆分复杂任务：问题
//     需不需要拆开思考（涉及多方面 / 有取舍 / 结果不确定 / 要探索迭代），
//     而不是"要做几步"。一个 10 步的机械活可能不需要 todo，一个 2 步的
//     重大决策可能非常需要。
//
// 教训（弃用的做法）：正则判"是否多步"、字数判"是否超短"、按"步骤/交付物"教模型判断
// ——都在按实现结构拍板，抓不住真正该拆解的任务。全部交给模型判断心智复杂度。

/** 开工前轻问一句：复杂任务就拆清单，简单直接就作答——由模型自行判断心智复杂度。 */
export function buildPlanPrompt(): string {
  return `[任务规划] todo 的作用是拆分复杂任务。如果你判断这个请求有较高复杂度——需要把一个较大的问题拆成几个子问题来思考和完成（涉及多个方面、存在权衡取舍、结果不确定、需要探索或迭代），即使实际步骤不多，也请先用 todo_write 把它拆成任务清单（每个子任务标注完成标准），再开始执行。清单是全程要结清的账本：每完成一个子任务就标为 completed 并把结果写进 result 字段（供面板和后续步骤使用），失败写原因，收尾把所有项结清。清单面板本身就是进度展示——除非用户明确要求，不要在回复正文里插入【进度汇报】式的机械分步汇报，保持正文自然连贯。如果任务简单直接（答案明确、一步完成、无需拆解），直接回答即可，无需建清单。并行执行决策：当存在多个待处理的子任务时，你可以考虑用 parallel_agent 工具并行执行相互独立的子任务（例如彼此之间没有依赖关系时）以提高效率；也可以考虑用 agent 工具按依赖顺序逐个执行。如何拆分、哪些并行、哪些串行，由你综合任务性质自主判断。`;
}

/** 每步同步提醒（rung-2 跟进）：有活跃 todo 时，每次决策前轻提一行，防止"只开工不跟进"。 */
export function buildTodoSyncReminder(): string {
  return `[任务同步] 若你已完成或正在进行某个子任务，用 todo_write 更新它的状态，并把结果写进 result 字段（结果写进清单即可，不要插入【进度汇报】式机械汇报；清单面板就是进度展示）。未列出的待办会被保留，放心只更新当前项。`;
}

/** 5 步兜底：干了几步还没建清单时提醒（不预判复杂度，由模型再判断一次）。 */
export function buildEmptyTodoReminder(): string {
  return `[任务清单为空] 已执行多步但仍未建立任务清单。如果这个任务较复杂、值得拆解推进，请先用 todo_write 建立清单再继续；如果确认简单直接，忽略本提醒继续完成即可。`;
}
