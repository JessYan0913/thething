// add: 返回两个数字之和。
// multiply: 返回两个数字之积。

/**
 * 返回两个数字之和。
 *
 * @param a - 第一个加数
 * @param b - 第二个加数
 * @returns `a + b`
 */
export function add(a: number, b: number): number {
  return a + b;
}

/**
 * 返回两个数字之积。
 *
 * @param a - 第一个因数
 * @param b - 第二个因数
 * @returns `a * b`
 */
export function multiply(a: number, b: number): number {
  return a * b;
}
